import { describe, expect, it } from "vitest"
import { createOrgWorkspaceEffectOwner } from "./org-workspace-effect-owner"

const setup = () => {
	const errors: string[] = []
	const owner = createOrgWorkspaceEffectOwner({ emitError: (message) => { errors.push(message) } })
	return { owner, errors }
}

describe("independent file effects and exclusive workspace barriers", () => {
	it("keeps disjoint captures independent while aggregate exit remains busy", () => {
		const { owner } = setup()
		const initialB = owner.getFileSnapshot("b.org")
		const a = owner.begin({ label: "save A", kind: "save", paths: ["a.org"] })
		const pendingA = Promise.withResolvers<boolean>()
		owner.captureSave(a, pendingA.promise, "captured A", "a.org")
		expect(owner.getFileSnapshot("b.org")).toBe(initialB)
		const b = owner.begin({ label: "save B", kind: "save", paths: ["b.org"] })
		const pendingB = Promise.withResolvers<boolean>()
		owner.captureSave(b, pendingB.promise, "captured B", "b.org")
		expect(owner.getFileSnapshot("a.org")).toMatchObject({ busy: true, saving: true, saveInFlight: pendingA.promise, capturedSaveContent: "captured A", claim: a })
		expect(owner.getFileSnapshot("b.org")).toMatchObject({ busy: true, saving: true, saveInFlight: pendingB.promise, capturedSaveContent: "captured B", claim: b })
		expect(owner.getSnapshot()).toMatchObject({ busy: true, globalBusy: false })
		expect(() => owner.begin({ label: "duplicate A", paths: ["a.org"] })).toThrow()
		expect(() => owner.begin({ label: "replace workspace", kind: "approval" })).toThrow()
		owner.finish(a)
		expect(owner.getFileSnapshot("a.org").busy).toBe(false)
		expect(owner.getFileSnapshot("b.org").saveInFlight).toBe(pendingB.promise)
		expect(owner.busy).toBe(true)
		expect(owner.finish(a)).toBe(false)
		owner.finish(b)
		expect(owner.busy).toBe(false)
	})

	it("keeps a related source reservation read-only while the captured save belongs only to its sidecar", () => {
		const { owner } = setup()
		const claim = owner.begin({ label: "remark", kind: "save", paths: ["source.org", "source-notes.org"] })
		const pending = Promise.withResolvers<boolean>()
		owner.captureSave(claim, pending.promise, "captured notes", "source-notes.org")
		expect(owner.getFileSnapshot("source.org")).toMatchObject({ busy: true, saveInFlight: null, capturedSaveContent: null })
		expect(owner.getFileSnapshot("source-notes.org")).toMatchObject({ busy: true, saveInFlight: pending.promise, capturedSaveContent: "captured notes" })
		expect(owner.getFileSnapshot("other.org").busy).toBe(false)
		owner.finish(claim)
		expect(owner.getFileSnapshot("source.org").busy).toBe(false)
		expect(owner.getFileSnapshot("source-notes.org").busy).toBe(false)
	})

	it("reserves a multi-file effect atomically and excludes ancestor directory mutations", () => {
		const { owner } = setup()
		const b = owner.begin({ label: "B", paths: ["notes/b.org"] })
		expect(() => owner.begin({ label: "move", paths: ["notes/a.org", "notes/b.org"] })).toThrow()
		expect(owner.getFileSnapshot("notes/a.org").busy).toBe(false)
		expect(() => owner.begin({ label: "directory", paths: ["notes"] })).toThrow()
		const unrelated = owner.begin({ label: "archive", paths: ["archive/a.org", "archive/b.org"] })
		expect(owner.owns(b)).toBe(true)
		expect(owner.owns(unrelated)).toBe(true)
		expect(owner.getFileSnapshot("archive/b.org").claim).toBe(unrelated)
	})

	it("freezes issued resource sets so caller mutation cannot move a native claim", () => {
		const { owner } = setup()
		const paths = ["a.org"]
		const a = owner.begin({ label: "A", paths })
		paths[0] = "b.org"
		expect(owner.getFileSnapshot("a.org").claim).toBe(a)
		expect(owner.getFileSnapshot("b.org").busy).toBe(false)
		expect(Object.isFrozen(owner.getSnapshot().claims[0].paths)).toBe(true)
		expect(Object.isFrozen(owner.getSnapshot())).toBe(true)
		expect(Object.isFrozen(owner.getFileSnapshot("a.org"))).toBe(true)
	})

	it("supersedes only a sole approval and stale finally cannot release its replacement", () => {
		const { owner } = setup()
		const read = owner.beginRead("open", ["a.org"])
		const first = owner.begin({ label: "approval", kind: "approval" })
		expect(read.isCurrent()).toBe(false)
		const second = owner.begin({ label: "approval", kind: "approval" })
		const snapshot = owner.getSnapshot()
		expect(owner.finish(first)).toBe(false)
		expect(owner.getSnapshot()).toBe(snapshot)
		expect(owner.getFileSnapshot("any.org")).toMatchObject({ loading: true, busy: true, claim: second })
		expect(() => owner.begin({ label: "file", paths: ["a.org"] })).toThrow()
		owner.finish(second)
		const mutation = owner.begin({ label: "file", paths: ["a.org"] })
		expect(() => owner.begin({ label: "approval", kind: "approval" })).toThrow()
		expect(owner.owns(mutation)).toBe(true)
	})

	it("retires only overlapping read channels and fences superseded/cancelled finally", () => {
		const { owner } = setup()
		const firstA = owner.beginRead("A1", ["a.org"], "window-a")
		const a = owner.beginRead("A2", ["a.org"], "window-a")
		const b = owner.beginRead("B", ["b.org"], "window-b")
		expect(firstA.finish()).toBe(false)
		owner.begin({ label: "save A", kind: "save", paths: ["a.org"] })
		expect(a.isCurrent()).toBe(false)
		expect(b.isCurrent()).toBe(true)
		expect(owner.getFileSnapshot("a.org").loading).toBe(false)
		expect(owner.getFileSnapshot("b.org").loading).toBe(true)
		expect(owner.cancelRead("window-b")).toBe(true)
		const replacement = owner.beginRead("B2", ["b.org"], "window-b")
		const current = owner.getSnapshot()
		expect(b.finish()).toBe(false)
		expect(owner.getSnapshot()).toBe(current)
		expect(replacement.isCurrent()).toBe(true)
	})

	it("a workspace barrier invalidates every read without reviving cancelled leases on replay", () => {
		const { owner } = setup()
		const a = owner.beginRead("A", ["a.org"], "a")
		const b = owner.beginRead("B", ["b.org"], "b")
		const global = owner.begin({ label: "index", presentation: "loading" })
		expect(a.isCurrent()).toBe(false)
		expect(b.isCurrent()).toBe(false)
		expect(owner.getSnapshot()).toMatchObject({ globalBusy: true, globalLoading: true })
		owner.finish(global)
		expect(a.finish()).toBe(false)
		expect(b.finish()).toBe(false)
		expect(owner.getFileSnapshot("a.org").loading).toBe(false)
	})

	it("publishes captured-save typing readiness synchronously without settling native promises", async () => {
		const { owner } = setup()
		let readOnly = false
		owner.subscribe(() => {
			const state = owner.getFileSnapshot("a.org")
			readOnly = state.loading || (state.busy && state.saveInFlight === null)
		})
		const native = Promise.withResolvers<boolean>()
		let delivered = false
		void native.promise.then(() => { delivered = true })
		const a = owner.begin({ label: "save", kind: "save", paths: ["a.org"] })
		expect(readOnly).toBe(true)
		expect(owner.captureSave(a, native.promise, "", "b.org")).toBe(false)
		expect(owner.captureSave(a, native.promise, "", "a.org")).toBe(true)
		expect(readOnly).toBe(false)
		expect(owner.getFileSnapshot("a.org").capturedSaveContent).toBe("")
		expect(owner.captureSave(a, Promise.resolve(false), "newer", "a.org")).toBe(false)
		owner.finish(a)
		expect(owner.getFileSnapshot("a.org").saveInFlight).toBeNull()
		await Promise.resolve()
		expect(delivered).toBe(false)
		native.resolve(true)
		await expect(native.promise).resolves.toBe(true)
	})

	it("batch waiters belong only to selected files and stale finish cannot drain a new batch", async () => {
		const { owner } = setup()
		const first = owner.begin({ label: "batch", kind: "save-all", paths: ["a.org", "b.org"] })
		expect(owner.captureBatch(first)).toBe(true)
		const waiter = owner.getFileSnapshot("a.org").saveInFlight!
		expect(owner.getFileSnapshot("b.org").saveInFlight).toBe(waiter)
		expect(owner.getFileSnapshot("c.org").busy).toBe(false)
		const c = owner.begin({ label: "C", paths: ["c.org"] })
		owner.finish(first)
		await expect(waiter).resolves.toBe(false)
		expect(owner.owns(c)).toBe(true)
		const second = owner.begin({ label: "batch", kind: "save-all", paths: ["a.org"] })
		owner.captureBatch(second)
		const next = owner.getFileSnapshot("a.org").saveInFlight!
		let delivered = false
		void next.then(() => { delivered = true })
		expect(owner.finish(first)).toBe(false)
		await Promise.resolve()
		expect(delivered).toBe(false)
		owner.dispose()
		await expect(next).resolves.toBe(false)
		expect(owner.owns(c)).toBe(false)
	})

	it("Agenda owns only its file read and stale releases cannot clear a peer save", () => {
		const { owner } = setup()
		const save = owner.begin({ label: "save B", kind: "save", paths: ["b.org"] })
		const first = owner.claimAgenda(["a.org"])
		first.startRead()
		expect(first.readIsCurrent()).toBe(true)
		expect(owner.getFileSnapshot("a.org").loading).toBe(true)
		expect(owner.getFileSnapshot("b.org").claim).toBe(save)
		const second = owner.claimAgenda(["a.org"])
		second.startRead()
		first.release()
		expect(first.finishRead()).toBe(false)
		expect(second.readIsCurrent()).toBe(true)
		second.release()
		expect(owner.getFileSnapshot("a.org").busy).toBe(false)
		expect(owner.getFileSnapshot("b.org").claim).toBe(save)
	})

	it.each(["finish", "dispose"] as const)("isolates observer failure while %s drains the exact batch", async (ending) => {
		const owner = createOrgWorkspaceEffectOwner({ emitError: () => { throw new Error("error observer") } })
		owner.subscribe(() => { throw new Error("snapshot observer") })
		const a = owner.begin({ label: "batch", kind: "save-all", paths: ["a.org"] })
		owner.captureBatch(a)
		const waiter = owner.getFileSnapshot("a.org").saveInFlight!
		if (ending === "finish") owner.finish(a)
		else owner.dispose()
		await expect(waiter).resolves.toBe(false)
		expect(owner.getFileSnapshot("a.org").busy).toBe(false)
	})

	it("disposes every authority before draining owned waiters but leaves external native IO unsettled", async () => {
		const { owner } = setup()
		const native = Promise.withResolvers<boolean>()
		let externalSettled = false
		void native.promise.then(() => { externalSettled = true })
		const a = owner.begin({ label: "save", kind: "save", paths: ["a.org"] })
		owner.captureSave(a, native.promise, "captured", "a.org")
		const b = owner.begin({ label: "batch", kind: "save-all", paths: ["b.org"] })
		owner.captureBatch(b)
		const waiter = owner.getFileSnapshot("b.org").saveInFlight!
		const read = owner.beginRead("C", ["c.org"])
		const agenda = owner.claimAgenda(["d.org"])
		owner.dispose()
		await expect(waiter).resolves.toBe(false)
		expect(externalSettled).toBe(false)
		expect(owner.owns(a)).toBe(false)
		expect(owner.owns(b)).toBe(false)
		expect(read.isCurrent()).toBe(false)
		expect(agenda.isCurrent()).toBe(false)
		const idle = owner.getSnapshot()
		owner.dispose()
		expect(owner.getSnapshot()).toBe(idle)
		owner.begin({ label: "replay", kind: "approval" })
		expect(read.finish()).toBe(false)
		expect(owner.getSnapshot().approving).toBe(true)
		native.resolve(true)
	})
})
