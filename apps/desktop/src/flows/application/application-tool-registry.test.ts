import { describe, expect, it, vi } from "vitest"
import { createApplicationToolRegistry, type ApplicationToolDescriptor } from "./application-tool-registry"
import { EMPTY_APPLICATION_POPUP_CONFIGURATION } from "./application-popup-configuration"

function descriptor(overrides: Partial<ApplicationToolDescriptor> = {}): ApplicationToolDescriptor {
	return { id: "scratch", label: "Real scratch", layout: "bottom", state: { dirty: false, pending: false, fence: 1 }, requestClose: () => true, ...overrides }
}

describe("independent application tool ownership", () => {
	it("invalidates a dirty close approval after placement ABA without changing the window or origin", async () => {
		const approval = Promise.withResolvers<boolean>()
		const close = vi.fn(() => true), restore = vi.fn()
		const registry = createApplicationToolRegistry(() => approval.promise)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ state: { dirty: true, pending: false, fence: 1 }, requestClose: close, captureOrigin: () => ({ isLive: () => true, restore }) }))
		registry.open(lease)
		const window = registry.getSnapshot()[0].windowId
		const closing = registry.close(lease)
		await Promise.resolve()
		registry.setConfiguration({ version: 1, rules: [{ id: "scratch", layout: "popup", size: { widthPercent: 60 } }] })
		registry.setConfiguration(EMPTY_APPLICATION_POPUP_CONFIGURATION)
		approval.resolve(true)
		expect(await closing).toBe(false)
		expect(close).not.toHaveBeenCalled()
		expect(registry.getSnapshot()[0]).toMatchObject({ open: true, windowId: window, layout: "bottom" })
		await registry.restoreOrigin(lease, window)
		expect(restore).toHaveBeenCalledOnce()
	})
	it("keeps accepted producer effects draining across placement changes", async () => {
		const effect = Promise.withResolvers<boolean>()
		const started = Promise.withResolvers<void>()
		const dispose = vi.fn()
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ requestClose: () => { started.resolve(); return effect.promise }, dispose }))
		registry.open(lease)
		const closing = registry.close(lease)
		await started.promise
		registry.setConfiguration({ version: 1, rules: [{ id: "scratch", layout: "side" }] })
		expect(registry.getSnapshot()[0]).toMatchObject({ open: true, closing: true })
		expect(dispose).not.toHaveBeenCalled()
		effect.resolve(true)
		expect(await closing).toBe(true)
		expect(dispose).toHaveBeenCalledOnce()
	})
	it("keeps stable identity while focusing and gives a reopened tool a different window", async () => {
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor())
		expect(registry.open(lease)).toBe(true)
		const first = registry.getSnapshot()[0].windowId
		registry.open(lease)
		expect(registry.getSnapshot()[0].windowId).toBe(first)
		expect(await registry.close(lease)).toBe(true)
		registry.open(lease)
		expect(registry.getSnapshot()[0].windowId).not.toBe(first)
	})
	it("fences stale window callbacks and remembers focus only within the exact current tool host", async () => {
		const source = document.createElement("textarea"), outside = document.createElement("button")
		const host = document.createElement("div"), first = document.createElement("textarea"), second = document.createElement("textarea")
		host.append(first, second); document.body.append(source, outside, host)
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ captureOrigin: () => ({ isLive: () => source.isConnected, restore: () => { source.focus() } }) }))
		source.focus(); registry.open(lease)
		const oldWindow = registry.getSnapshot()[0].windowId
		registry.bindHost(lease, host, oldWindow)
		expect(first).toHaveFocus()
		second.focus(); registry.recordFocus(lease, second); outside.focus()
		expect(registry.focus(lease, oldWindow)).toBe(true)
		expect(second).toHaveFocus()
		expect(await registry.close(lease, oldWindow)).toBe(true)
		expect(source).toHaveFocus()
		registry.open(lease)
		const currentWindow = registry.getSnapshot()[0].windowId
		expect(await registry.close(lease, oldWindow)).toBe(false)
		expect(registry.complete(lease, oldWindow)).toBe(false)
		expect(registry.focus(lease, oldWindow)).toBe(false)
		expect(registry.getSnapshot()[0]).toMatchObject({ open: true, windowId: currentWindow })
		registry.bindHost(lease, host, currentWindow)
		expect(first).toHaveFocus()
		await registry.retire(lease)
		source.remove(); outside.remove(); host.remove()
	})
	it("returns from the producer's exact root parameter focus without treating unrelated root focus as owned", async () => {
		const source = document.createElement("textarea"), parameter = document.createElement("input")
		document.body.append(source, parameter)
		const restore = vi.fn(() => source.focus())
		let ownsParameter = true
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ ownsFocus: () => ownsParameter && document.activeElement === parameter, captureOrigin: () => ({ isLive: () => true, restore }) }))
		registry.open(lease); parameter.focus()
		expect(await registry.close(lease)).toBe(true)
		expect(source).toHaveFocus()
		registry.open(lease); parameter.focus(); ownsParameter = false
		expect(await registry.close(lease)).toBe(true)
		expect(restore).toHaveBeenCalledTimes(1)
		expect(parameter).toHaveFocus()
		source.remove(); parameter.remove()
	})
	it("cancelled discard keeps the real producer draft and never calls its close or dispose", async () => {
		const close = vi.fn(() => true), dispose = vi.fn()
		const registry = createApplicationToolRegistry(async () => false)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ state: { dirty: true, pending: false, fence: "literal draft" }, requestClose: close, dispose }))
		registry.open(lease)
		expect(await registry.close(lease)).toBe(false)
		expect(registry.getSnapshot()[0]).toMatchObject({ open: true, closing: false, state: { dirty: true, fence: "literal draft" } })
		expect(close).not.toHaveBeenCalled()
		expect(dispose).not.toHaveBeenCalled()
	})
	it("invalidates discard approvals on draft/grant ABA even when the old value reappears", async () => {
		const approval = Promise.withResolvers<boolean>()
		const close = vi.fn(() => true)
		const registry = createApplicationToolRegistry(() => approval.promise)
		const lease = registry.createLease({}, "scratch")
		const original = descriptor({ state: { dirty: true, pending: false, fence: "G1:draft" }, requestClose: close })
		registry.register(lease, original); registry.open(lease)
		const result = registry.close(lease)
		await Promise.resolve()
		registry.update(lease, { ...original, state: { ...original.state, fence: "G2:draft" } })
		registry.update(lease, original)
		approval.resolve(true)
		expect(await result).toBe(false)
		expect(close).not.toHaveBeenCalled()
		expect(registry.getSnapshot()[0].open).toBe(true)
	})
	it("retired same-ID callbacks cannot close replacement owners", async () => {
		const approval = Promise.withResolvers<boolean>()
		const close = vi.fn(() => true)
		const registry = createApplicationToolRegistry(() => approval.promise)
		const owner = {}, old = registry.createLease(owner, "scratch")
		registry.register(old, descriptor({ state: { dirty: true, pending: false, fence: 1 }, requestClose: close }))
		registry.open(old)
		const pending = registry.close(old)
		await Promise.resolve()
		const retiring = registry.retire(old)
		const replacement = registry.createLease(owner, "scratch")
		registry.register(replacement, descriptor()); registry.open(replacement)
		approval.resolve(true)
		expect(await pending).toBe(false)
		await retiring
		expect(close).not.toHaveBeenCalled()
		expect(registry.open(old)).toBe(false)
		expect(registry.getSnapshot()[0]).toMatchObject({ lease: replacement, open: true })
	})
	it("drains an accepted asynchronous producer close before disposing on retirement", async () => {
		const accepted = Promise.withResolvers<boolean>()
		const close = vi.fn(() => accepted.promise), dispose = vi.fn()
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ requestClose: close, dispose })); registry.open(lease)
		const result = registry.close(lease)
		await Promise.resolve()
		expect(close).toHaveBeenCalledOnce()
		const retirement = registry.retire(lease)
		expect(dispose).not.toHaveBeenCalled()
		accepted.resolve(true)
		expect(await result).toBe(true)
		await retirement
		expect(dispose).toHaveBeenCalledOnce()
		expect(registry.getSnapshot()).toEqual([])
	})
	it("refuses dismissal during a started accepted effect rather than pretending to cancel it", async () => {
		const close = vi.fn(() => true), approval = vi.fn(async () => true)
		const registry = createApplicationToolRegistry(approval)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ state: { dirty: true, pending: true, fence: 1 }, requestClose: close })); registry.open(lease)
		expect(await registry.close(lease)).toBe(false)
		expect(close).not.toHaveBeenCalled()
		expect(approval).not.toHaveBeenCalled()
	})
	it("singleflights a close and never recaptures the origin at its later completion", async () => {
		const approval = Promise.withResolvers<boolean>()
		const captureOrigin = vi.fn(() => null)
		const registry = createApplicationToolRegistry(() => approval.promise)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ state: { dirty: true, pending: false, fence: 1 }, captureOrigin })); registry.open(lease)
		const a = registry.close(lease), b = registry.close(lease)
		approval.resolve(true)
		expect(await a).toBe(true); expect(await b).toBe(true)
		expect(captureOrigin).toHaveBeenCalledOnce()
	})
	it("does not dispose a producer during StrictMode-style exact-lease reattachment", async () => {
		const dispose = vi.fn()
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ dispose }))
		const retiring = registry.retire(lease)
		registry.register(lease, descriptor({ dispose }))
		await retiring
		expect(dispose).not.toHaveBeenCalled()
		expect(registry.getSnapshot()).toHaveLength(1)
	})
	it("returns to its exact surviving origin, not a later source selection or a removed window", async () => {
		const first = document.createElement("textarea"), second = document.createElement("textarea")
		const host = document.createElement("div"), draft = document.createElement("textarea")
		host.append(draft); document.body.append(first, second, host)
		let selected = first
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ captureOrigin: () => {
			const captured = selected
			return { isLive: () => captured.isConnected, restore: () => { captured.focus() } }
		} }))
		registry.open(lease); registry.bindHost(lease, host)
		selected = second; draft.focus()
		expect(await registry.close(lease)).toBe(true)
		expect(first).toHaveFocus()
		selected = first; registry.open(lease)
		first.remove(); draft.focus()
		expect(await registry.close(lease)).toBe(true)
		expect(second).not.toHaveFocus()
		second.remove(); host.remove()
	})
	it("does not steal focus from a surviving unrelated window when a tool closes", async () => {
		const source = document.createElement("textarea"), other = document.createElement("textarea")
		const host = document.createElement("div"), draft = document.createElement("textarea")
		host.append(draft); document.body.append(source, other, host)
		const restore = vi.fn(() => source.focus())
		const registry = createApplicationToolRegistry(async () => true)
		const lease = registry.createLease({}, "scratch")
		registry.register(lease, descriptor({ captureOrigin: () => ({ isLive: () => true, restore }) }))
		registry.open(lease); registry.bindHost(lease, host)
		other.focus()
		expect(await registry.close(lease)).toBe(true)
		expect(restore).not.toHaveBeenCalled()
		expect(other).toHaveFocus()
		source.remove(); other.remove(); host.remove()
	})
})
